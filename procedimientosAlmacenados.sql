CREATE OR REPLACE PROCEDURE PRODUCTOS_MAS_VENDIDOS( 
  P_LIMITE IN NUMBER,
  P_RESULTADO OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN P_RESULTADO FOR
    SELECT P.PRODUCTO_ID,
           P.NOMBRE,
           SUM(D.CANTIDAD) AS TOTAL_VENDIDO
    FROM DETALLE_PEDIDO D
    JOIN PRODUCTOS P ON D.PRODUCTO_ID = P.PRODUCTO_ID
    GROUP BY P.PRODUCTO_ID, P.NOMBRE
    ORDER BY TOTAL_VENDIDO DESC
    FETCH FIRST P_LIMITE ROWS ONLY;

  DBMS_OUTPUT.PUT_LINE('CONSULTA GENERADA: PRODUCTOS MÁS VENDIDOS (TOP ' || P_LIMITE || ')');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR AL CONSULTAR PRODUCTOS MAS VENDIDOS: ' || SQLERRM);
END;
/

DECLARE
  V_CURSOR SYS_REFCURSOR;
  V_ID NUMBER;
  V_NOMBRE VARCHAR2(100);
  V_TOTAL NUMBER;
BEGIN
  PRODUCTOS_MAS_VENDIDOS(5, V_CURSOR);

  LOOP
    FETCH V_CURSOR INTO V_ID, V_NOMBRE, V_TOTAL;
    EXIT WHEN V_CURSOR%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE('PRODUCTO: ' || V_NOMBRE || ' - VENDIDOS: ' || V_TOTAL);
  END LOOP;
END;
/

--Procedimiento almacenado 18 
CREATE OR REPLACE PROCEDURE PRODUCTOS_BAJO_STOCK(
  P_RESULTADO OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN P_RESULTADO FOR
    SELECT P.PRODUCTO_ID,
           P.NOMBRE,
           I.EXISTENCIAS,
           I.STOCK_MINIMO
    FROM INVENTARIO I
    JOIN PRODUCTOS P ON I.PRODUCTO_ID = P.PRODUCTO_ID
    WHERE I.EXISTENCIAS <= I.STOCK_MINIMO;

  DBMS_OUTPUT.PUT_LINE('CONSULTA GENERADA: PRODUCTOS BAJO STOCK');
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR AL CONSULTAR BAJO STOCK: ' || SQLERRM);
END;
/

DECLARE
  V_CURSOR SYS_REFCURSOR;
  V_ID NUMBER;
  V_NOMBRE VARCHAR2(100);
  V_EX NUMBER;
  V_MIN NUMBER;
BEGIN
  PRODUCTOS_BAJO_STOCK(V_CURSOR);

  LOOP
    FETCH V_CURSOR INTO V_ID, V_NOMBRE, V_EX, V_MIN;
    EXIT WHEN V_CURSOR%NOTFOUND;
    DBMS_OUTPUT.PUT_LINE('PRODUCTO: ' || V_NOMBRE || ' EXISTENCIAS: ' || V_EX);
  END LOOP;
END;
/

