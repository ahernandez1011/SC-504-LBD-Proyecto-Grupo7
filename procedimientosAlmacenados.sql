CREATE OR REPLACE PROCEDURE REPORTE_VENTAS_FECHA( 
  P_FECHA_INICIO IN DATE,
  P_FECHA_FIN IN DATE,
  P_TOTAL OUT NUMBER
) AS
BEGIN
  SELECT NVL(SUM(TOTAL), 0)
  INTO P_TOTAL
  FROM FACTURAS
  WHERE FECHA BETWEEN P_FECHA_INICIO AND P_FECHA_FIN;

  DBMS_OUTPUT.PUT_LINE('REPORTE DE VENTAS');
  DBMS_OUTPUT.PUT_LINE('- DESDE: ' || TO_CHAR(P_FECHA_INICIO, 'DD/MM/YYYY'));
  DBMS_OUTPUT.PUT_LINE('- HASTA: ' || TO_CHAR(P_FECHA_FIN, 'DD/MM/YYYY'));
  DBMS_OUTPUT.PUT_LINE('- TOTAL VENTAS: $' || P_TOTAL);

EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR AL GENERAR REPORTE: ' || SQLERRM);
END;
/

DECLARE
  V_TOTAL NUMBER;
BEGIN
  REPORTE_VENTAS_FECHA(SYSDATE - 30, SYSDATE, V_TOTAL);
  DBMS_OUTPUT.PUT_LINE('VENTAS TOTALES: ' || V_TOTAL);
END;
