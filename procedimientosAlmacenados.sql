CREATE OR REPLACE PROCEDURE VENTAS_POR_EMPLEADO(
  P_EMPLEADO_ID IN NUMBER,
  P_TOTAL OUT NUMBER
) AS
BEGIN
  SELECT SUM(F.TOTAL)
  INTO P_TOTAL
  FROM FACTURAS F
  JOIN PEDIDOS P ON F.PEDIDO_ID = P.PEDIDO_ID
  WHERE P.EMPLEADO_ID = P_EMPLEADO_ID;
END;
/

