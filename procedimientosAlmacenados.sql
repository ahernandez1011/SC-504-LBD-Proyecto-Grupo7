--Procedimiento almacenado 13
CREATE OR REPLACE PROCEDURE GENERAR_FACTURA( 
  P_PEDIDO_ID IN NUMBER,
  P_DESCUENTO IN NUMBER DEFAULT 0
) AS
  V_TOTAL NUMBER;
  V_TOTAL_DESCONTADO NUMBER;
BEGIN
  -- Obtener total del pedido
  CALCULAR_TOTAL_PEDIDO(P_PEDIDO_ID, V_TOTAL);

  -- Aplicar descuento
  V_TOTAL_DESCONTADO := V_TOTAL - (V_TOTAL * (P_DESCUENTO / 100));

  -- Insertar factura
  INSERT INTO FACTURAS (PEDIDO_ID, FECHA, TOTAL, DESCUENTO_APLICADO)
  VALUES (P_PEDIDO_ID, SYSDATE, V_TOTAL_DESCONTADO, P_DESCUENTO);

  -- SALIDA
  DBMS_OUTPUT.PUT_LINE('FACTURA GENERADA:');
  DBMS_OUTPUT.PUT_LINE('- PEDIDO: ' || P_PEDIDO_ID);
  DBMS_OUTPUT.PUT_LINE('- SUBTOTAL: $' || V_TOTAL);
  DBMS_OUTPUT.PUT_LINE('- DESCUENTO: ' || P_DESCUENTO || '%');
  DBMS_OUTPUT.PUT_LINE('- TOTAL FACTURADO: $' || V_TOTAL_DESCONTADO);
  DBMS_OUTPUT.PUT_LINE('- FECHA: ' || TO_CHAR(SYSDATE, 'DD/MM/YYYY HH24:MI'));

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('ERROR: EL PEDIDO NO EXISTE (' || P_PEDIDO_ID || ')');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR AL GENERAR FACTURA: ' || SQLERRM);
END;
/

BEGIN
  GENERAR_FACTURA(1, 10);
END;
/

