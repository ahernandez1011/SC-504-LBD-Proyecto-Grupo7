--Procedimiento almacenado 17 
CREATE OR REPLACE PROCEDURE PRODUCTOS_MAS_VENDIDOS(
  P_LIMITE IN NUMBER,
  P_RESULTADO OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN P_RESULTADO FOR
    SELECT P.PRODUCTO_ID,
           P.NOMBRE,
           SUM(D.CANTIDAD) AS TOTAL_VENDIDO
    FROM DETALLE_PEDIDO D
    JOIN PRODUCTOS P ON D.PRODUCTO_ID = P.PRODUCTO_ID
    GROUP BY P.PRODUCTO_ID, P.NOMBRE
    ORDER BY TOTAL_VENDIDO DESC
    FETCH FIRST P_LIMITE ROWS ONLY;
END;
/

VARIABLE rc REFCURSOR;
EXEC PRODUCTOS_MAS_VENDIDOS(5, :rc);
PRINT rc;

--Procedimiento almacenado 18 
CREATE OR REPLACE PROCEDURE PRODUCTOS_BAJO_STOCK(
  P_RESULTADO OUT SYS_REFCURSOR
) AS
BEGIN
  OPEN P_RESULTADO FOR
    SELECT P.PRODUCTO_ID,
           P.NOMBRE,
           I.EXISTENCIAS,
           I.STOCK_MINIMO
    FROM INVENTARIO I
    JOIN PRODUCTOS P ON I.PRODUCTO_ID = P.PRODUCTO_ID
    WHERE I.EXISTENCIAS <= I.STOCK_MINIMO;
END;
/

VARIABLE rc REFCURSOR;
EXEC PRODUCTOS_BAJO_STOCK(:rc);
PRINT rc;

