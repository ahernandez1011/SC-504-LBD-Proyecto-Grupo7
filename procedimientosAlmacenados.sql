--Procedimiento almacenado 11
CREATE OR REPLACE PROCEDURE AGREGAR_DETALLE_PEDIDO(
  P_PEDIDO_ID IN NUMBER,
  P_PRODUCTO_ID IN NUMBER,
  P_CANTIDAD IN NUMBER
) AS
  V_PRECIO NUMBER;
BEGIN
  SELECT PRECIO INTO V_PRECIO FROM PRODUCTOS WHERE PRODUCTO_ID = P_PRODUCTO_ID;

  INSERT INTO DETALLE_PEDIDO (PEDIDO_ID, PRODUCTO_ID, CANTIDAD, SUBTOTAL)
  VALUES (P_PEDIDO_ID, P_PRODUCTO_ID, P_CANTIDAD, P_CANTIDAD * V_PRECIO);

  UPDATE INVENTARIO
  SET EXISTENCIAS = EXISTENCIAS - P_CANTIDAD
  WHERE PRODUCTO_ID = P_PRODUCTO_ID;
END;
/

--Procedimiento almacenado 12
CREATE OR REPLACE PROCEDURE CALCULAR_TOTAL_PEDIDO(
  P_PEDIDO_ID IN NUMBER,
  P_TOTAL OUT NUMBER
) AS
BEGIN
  SELECT SUM(SUBTOTAL)
  INTO P_TOTAL
  FROM DETALLE_PEDIDO
  WHERE PEDIDO_ID = P_PEDIDO_ID;
END;
/

--Procedimiento almacenado 13
CREATE OR REPLACE PROCEDURE GENERAR_FACTURA(
  P_PEDIDO_ID IN NUMBER,
  P_DESCUENTO IN NUMBER DEFAULT 0
) AS
  V_TOTAL NUMBER;
BEGIN
  CALCULAR_TOTAL_PEDIDO(P_PEDIDO_ID, V_TOTAL);
  V_TOTAL := V_TOTAL - (V_TOTAL * (P_DESCUENTO / 100));

  INSERT INTO FACTURAS (PEDIDO_ID, FECHA, TOTAL, DESCUENTO_APLICADO)
  VALUES (P_PEDIDO_ID, SYSDATE, V_TOTAL, P_DESCUENTO);
END;
/

