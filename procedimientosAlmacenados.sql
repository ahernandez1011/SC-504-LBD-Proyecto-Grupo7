CREATE OR REPLACE PROCEDURE VALIDAR_USUARIO(
  P_USUARIO IN VARCHAR2,
  P_CONTRASENA IN VARCHAR2,
  P_VALIDO OUT NUMBER
) AS
  V_COUNT NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_COUNT
  FROM EMPLEADOS
  WHERE USUARIO = P_USUARIO AND CONTRASENA = P_CONTRASENA;

  P_VALIDO := CASE WHEN V_COUNT > 0 THEN 1 ELSE 0 END;

  IF P_VALIDO = 1 THEN
