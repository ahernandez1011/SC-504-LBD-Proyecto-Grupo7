CREATE OR REPLACE PROCEDURE AGREGAR_DETALLE_PEDIDO( 
  P_PEDIDO_ID IN NUMBER,
  P_PRODUCTO_ID IN NUMBER,
  P_CANTIDAD IN NUMBER
) AS
  V_PRECIO NUMBER;
BEGIN
  -- Obtener precio del producto
  SELECT PRECIO INTO V_PRECIO 
  FROM PRODUCTOS 
  WHERE PRODUCTO_ID = P_PRODUCTO_ID;

  -- Insertar detalle
  INSERT INTO DETALLE_PEDIDO (PEDIDO_ID, PRODUCTO_ID, CANTIDAD, SUBTOTAL)
  VALUES (P_PEDIDO_ID, P_PRODUCTO_ID, P_CANTIDAD, P_CANTIDAD * V_PRECIO);

  -- Actualizar inventario
  UPDATE INVENTARIO
  SET EXISTENCIAS = EXISTENCIAS - P_CANTIDAD
  WHERE PRODUCTO_ID = P_PRODUCTO_ID;

  DBMS_OUTPUT.PUT_LINE('DETALLE AGREGADO:');
  DBMS_OUTPUT.PUT_LINE('- PEDIDO: ' || P_PEDIDO_ID);
  DBMS_OUTPUT.PUT_LINE('- PRODUCTO: ' || P_PRODUCTO_ID);
  DBMS_OUTPUT.PUT_LINE('- CANTIDAD: ' || P_CANTIDAD);
  DBMS_OUTPUT.PUT_LINE('- SUBTOTAL: $' || (P_CANTIDAD * V_PRECIO));

EXCEPTION
  WHEN NO_DATA_FOUND THEN
    DBMS_OUTPUT.PUT_LINE('ERROR: PRODUCTO NO EXISTE (' || P_PRODUCTO_ID || ')');
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('ERROR AL INSERTAR DETALLE: ' || SQLERRM);
END;
/

BEGIN
  AGREGAR_DETALLE_PEDIDO(1, 1, 3);
END;
/

